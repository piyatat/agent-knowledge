#!/usr/bin/env node
/**
 * Regenerate DIRECTORY.md from manifest.json: a compact, kind-grouped catalog
 * of tools, services and protocols (one line each) for planning-time lookup.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(join(root, "manifest.json"), "utf8"));
const entries = (manifest.entries ?? []).filter((e) => e.status !== "deprecated");

const SECTIONS = [
  ["tool", "Tools", "Installable agents, CLIs, SDKs, IDE integrations and plugins."],
  ["service", "Services", "Hosted platforms, cloud agents, integrations and managed features."],
  ["protocol", "Protocols and standards", "Open specs agents and tools use to talk to each other."],
];

const clip = (s, n = 110) => {
  const t = (s ?? "—").replace(/\|/g, "/");
  return t.length > n ? t.slice(0, n - 1).trimEnd() + "…" : t;
};

const lines = [
  "# Directory",
  "",
  "<!-- Generated by `npm run directory` from manifest.json — do not edit by hand. -->",
  "",
  "Look here **before acting or while planning**: find the tool, service or protocol that already covers the job, then open its note. For free-text lookup run `npm run lookup -- \"<task>\"`. Knowledge/practice notes are in `INDEX.md`.",
  "",
];

for (const [kind, heading, blurb] of SECTIONS) {
  const group = entries.filter((e) => e.kind === kind);
  lines.push(`## ${heading} (${group.length})`, "", blurb, "");
  lines.push("| id | use when | tags | status |", "| --- | --- | --- | --- |");
  for (const e of group) {
    lines.push(
      `| [${e.id}](${e.path}) | ${clip(e.when_to_use)} | ${(e.tags ?? []).slice(0, 4).join(", ")} | ${e.status} |`,
    );
  }
  lines.push("");
}

writeFileSync(join(root, "DIRECTORY.md"), lines.join("\n"), "utf8");
console.log(`Wrote DIRECTORY.md (${entries.filter((e) => e.kind && e.kind !== "knowledge").length} entries)`);
